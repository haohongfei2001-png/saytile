#!/bin/bash
set -euo pipefail
cd "$(dirname "$0")/.."
configuration="${1:-release}"
swift build -c "$configuration"
bin_dir="$(swift build -c "$configuration" --show-bin-path)"
app="$PWD/dist/Saytile.app"
mkdir -p "$app/Contents/MacOS" "$app/Contents/Resources"
cp "$bin_dir/Saytile" "$app/Contents/MacOS/Saytile"
swift scripts/make-icon.swift "$PWD/dist/Saytile.iconset"
iconutil -c icns "$PWD/dist/Saytile.iconset" -o "$app/Contents/Resources/Saytile.icns"
cp THIRD_PARTY_NOTICES.md "$app/Contents/Resources/THIRD_PARTY_NOTICES.md"
cp Sources/CAudio/WEBRTC-LICENSE.txt "$app/Contents/Resources/WEBRTC-LICENSE.txt"
cp packaging/Info.plist "$app/Contents/Info.plist"
/usr/libexec/PlistBuddy -c "Add :SaytileSourceRevision string $(git rev-parse HEAD)" "$app/Contents/Info.plist"
/usr/libexec/PlistBuddy -c "Set :CFBundleVersion $(git rev-list --count HEAD)" "$app/Contents/Info.plist"
xattr -cr "$app"
codesign --force --sign "${SAYTILE_SIGN_IDENTITY:--}" --timestamp=none "$app"
codesign --verify --strict "$app"
plutil -lint "$app/Contents/Info.plist"
printf 'Built %s\n' "$app"
